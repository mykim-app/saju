// order: 이 화면에서 실제로 쓰는 용어만, 나오는 순서대로 넣어 주면 그 순서로 보여 준다.
export function glossarySection(order) {
  const items = order.filter((k) => GLOSSARY[k]);
  if (!items.length) return "";
  return `
  <section class="rsec glossary" data-pdf-block>
    <h2>어려운 말 풀이</h2>
    <div class="tglegend">
      <ul class="glossary-list">${items.map((k) => `<li><b>${k}</b> ${GLOSSARY[k]}</li>`).join("")}</ul>
    </div>
  </section>`;
}
